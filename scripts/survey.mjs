// The living survey: starts a fixed list of well-known MCP servers in the real Claude Code with mcp-proof and writes a dated page
// and one compat.json per server. Used by .github/workflows/survey.yml (a job with a read-only token); the page and records are
// published by a separate job that runs none of this code.
//
// How each server is run (the same as the hand-run survey in survey/2026-11/): installed into its own folder with install scripts
// OFF at its latest version, then started with `node <its bin file>`, not with npx. No credentials are given to any server. A result
// that is not `verified` is run once more before it is written down. It is a sample, not a ranking, and says so.
//
//   node scripts/survey.mjs --servers survey/servers.json --work <dir> --out <dir> [--mcp-proof dist/main.js]
import { spawnSync } from "node:child_process";
import { copyFileSync, existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

/** The file a package starts (its bin), relative and without a leading ./, or undefined when there is none or it points outside. */
export function resolveBin(pkg) {
  const bin = pkg.bin;
  let value;
  if (typeof bin === "string") value = bin;
  else if (bin && typeof bin === "object") {
    const unscoped = String(pkg.name ?? "").split("/").pop();
    value = bin[unscoped] ?? Object.values(bin)[0];
  }
  if (typeof value !== "string" || value === "") return undefined;
  const clean = value.replace(/^\.\//, "");
  if (clean.startsWith("/") || /^[A-Za-z]:/.test(clean) || clean.split("/").includes("..")) return undefined;
  return clean;
}

/** Which handshake a log shows: server/discover, initialize, both (in that order) or a dash. */
export function handshakeOf(methods) {
  const seen = ["server/discover", "initialize"].filter((method) => methods.includes(method));
  return seen.length > 0 ? seen.join(", ") : "-";
}

/** @param {{date:string, claudeCode:string, mcpProof:string, system:string, rows:Array<{slug:string,pkg:string,version:string,claude:string,standin:string,handshake:string,note:string}>}} data */
export function renderSurvey({ date, claudeCode, mcpProof, system, rows }) {
  const table = rows.map((r) => `| \`${r.pkg}\` ${r.version} | ${r.handshake} | ${r.claude} | ${r.standin} | ${r.note} |`);
  return [
    `# Do well-known MCP servers start in Claude Code? Automated run, ${date}`,
    "",
    `Each server below was installed at its latest version and started by the real Claude Code ${claudeCode} on ${system}, with mcp-proof ${mcpProof}. This page is regenerated by a workflow; the hand-run survey with the full method is [survey/2026-11](https://github.com/voyageurworks/mcp-proof/blob/main/survey/2026-11/README.md).`,
    "",
    "`verified` means the client started the server, the handshake was answered and `tools/list` was answered. It does **not** mean a tool was called, that a tool returns the right thing, or that the server works in another client, on another system or with a login.",
    "",
    "| Server (npm package and version) | Handshake | Claude Code | mcp-proof stand-in client | Note |",
    "| --- | --- | --- | --- | --- |",
    ...table,
    "",
    "## Read this before drawing a conclusion",
    "",
    "- It is a sample, not a ranking, and says nothing about the quality of a project. A result that did not verify in this run was run once more before it was written down; the records next to this page hold the exact commands and method names seen, and the reason mcp-proof gives.",
    "- One real client (Claude Code) on one system. Servers were installed with install scripts off and started with `node`, not `npx`. No credentials were given to any server, so what a tool does with a key was not tested.",
    "- The throwaway homes were deleted after each run.",
    "",
  ].join("\n");
}

function parse(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2) args[argv[i].replace(/^--/, "")] = argv[i + 1];
  return args;
}

const run = (command, args, options = {}) =>
  spawnSync(command, args, { encoding: "utf8", shell: process.platform === "win32" && command === "npm", ...options });

export function main(argv) {
  const args = parse(argv);
  const servers = JSON.parse(readFileSync(args.servers ?? "survey/servers.json", "utf8"));
  const work = path.resolve(args.work ?? "survey-work");
  const out = path.resolve(args.out ?? "survey-out");
  const mcpProof = path.resolve(args["mcp-proof"] ?? "dist/main.js");
  mkdirSync(work, { recursive: true });
  mkdirSync(out, { recursive: true });

  const rows = [];
  let claudeCode = "";
  let mcpProofVersion = "";
  let system = "";
  for (const server of servers) {
    const dir = path.join(work, server.slug);
    mkdirSync(dir, { recursive: true });
    writeFileSync(path.join(dir, "package.json"), JSON.stringify({ name: `survey-${server.slug}`, private: true }));
    const row = { slug: server.slug, pkg: server.package, version: "", claude: "not run", standin: "not run", handshake: "-", note: "" };
    rows.push(row);

    const install = run("npm", ["install", "--ignore-scripts", "--no-audit", "--no-fund", "--loglevel=error", `${server.package}@latest`], { cwd: dir, timeout: 240_000 });
    const manifest = path.join(dir, "node_modules", ...server.package.split("/"), "package.json");
    if (install.status !== 0 || !existsSync(manifest)) {
      row.note = "install did not complete";
      continue;
    }
    const pkg = JSON.parse(readFileSync(manifest, "utf8"));
    row.version = String(pkg.version ?? "");
    const entry = resolveBin(pkg);
    if (!entry) {
      row.note = "no start file (bin) in the package";
      continue;
    }

    const record = path.join(out, `${server.slug}.compat.json`);
    const attempt = () => {
      const result = run(process.execPath, [mcpProof, "run", "--client", "claude-code", "--client", "standin", "--timeout", "150", "--out", path.join(work, `proof-${server.slug}`), "--cwd", dir, "--", "node", path.posix.join("node_modules", ...server.package.split("/"), entry), ...(server.args ?? [])], { timeout: 420_000 });
      const file = path.join(work, `proof-${server.slug}`, "compat.json");
      return result.status !== 2 && existsSync(file) ? JSON.parse(readFileSync(file, "utf8")) : undefined;
    };
    let compat = attempt();
    let result = compat?.results.find((r) => r.client === "claude-code");
    if (compat && result && result.label !== "verified" && result.label !== "not-installed") {
      const again = attempt();
      const againResult = again?.results.find((r) => r.client === "claude-code");
      if (again && againResult) {
        compat = again;
        result = againResult;
        row.note = "re-run once";
      }
    }
    if (!compat || !result) {
      row.note = "mcp-proof did not produce a record";
      continue;
    }
    const standin = compat.results.find((r) => r.client === "standin");
    row.claude = result.label === "verified" ? "verified" : `${result.label}; did not verify in this run`;
    row.standin = standin?.label ?? "not run";
    row.handshake = handshakeOf(result.methods ?? []);
    claudeCode ||= result.clientVersion ?? "";
    mcpProofVersion ||= compat.version ?? "";
    system ||= `${compat.system.os} ${compat.system.arch}, Node ${String(compat.system.node).replace(/^v/, "")}`;
    copyFileSync(path.join(work, `proof-${server.slug}`, "compat.json"), record);
    if (run(process.execPath, [mcpProof, "validate", record]).status !== 0) row.note = [row.note, "record did not validate"].filter(Boolean).join("; ");
  }

  const ran = rows.filter((r) => r.claude !== "not run");
  const date = new Date().toISOString().slice(0, 10);
  writeFileSync(path.join(out, "README.md"), renderSurvey({ date, claudeCode: claudeCode || "(not found)", mcpProof: mcpProofVersion || "(unknown)", system: system || "(unknown)", rows }));
  console.log(rows.map((r) => `${r.slug}: ${r.claude}${r.note ? ` (${r.note})` : ""}`).join("\n"));
  // A run where Claude Code did not run at all is not a survey: fail so the publishing job does not replace good data with nothing.
  if (ran.length === 0 || !claudeCode) process.exitCode = 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) main(process.argv.slice(2));
